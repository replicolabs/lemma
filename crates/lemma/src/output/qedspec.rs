use std::fmt::Write;
use crate::types::{HandlerInvariants, QedSpecClause};

pub fn generate(
    program_name:   &str,
    program_id:     Option<&str>,
    invariants_list: &[HandlerInvariants],
) -> String {
    let mut out = String::with_capacity(2048);
    out.push_str("// Generated by Lemma — automated Solana security analysis\n");
    out.push_str("// Review all clauses before using with `qedgen check`.\n");
    out.push_str("// Clauses marked TODO require manual completion.\n");
    out.push_str("// Commented-out clauses failed kani compilation — review before enabling.\n");
    out.push('\n');
    let spec_name = to_pascal_case(program_name);
    writeln!(out, "spec {}", spec_name).ok();

    if let Some(id) = program_id {
        writeln!(out, "program_id \"{}\"", id).ok();
    }
    out.push('\n');

    if invariants_list.is_empty() {
        out.push_str("// No handlers found — ensure the parser detected your instruction functions.\n");
        return out;
    }
    for handler_inv in invariants_list {
        write_handler_block(&mut out, handler_inv);
    }

    out
}

fn write_handler_block(out: &mut String, inv: &HandlerInvariants) {
    writeln!(
        out,
        "handler {} : State.Active -> State.Active {{",
        inv.handler_name
    )
    .ok();

    if inv.natural_language.is_empty() && inv.qedspec_forms.is_empty() {
        writeln!(out, "  // TODO: add invariants for this handler").ok();
    } else {
        if !inv.natural_language.is_empty() {
            writeln!(out, "  // {}", inv.natural_language).ok();
            if inv.grounded_in.len() > 0 {
                writeln!(out, "  // Grounded in: {}", inv.grounded_in).ok();
            }
            writeln!(out, "  // Confidence: {:.0}%", inv.confidence * 100.0).ok();
        }

        for clause in &inv.qedspec_forms {
            write_clause(out, clause, inv.kani_valid);
        }

        if !inv.kani_assertion.is_empty() {
            writeln!(out).ok();
            writeln!(out, "  // Kani equivalent:").ok();
            for line in inv.kani_assertion.lines() {
                writeln!(out, "  //   {}", line).ok();
            }
        }
    }

    writeln!(out, "}}").ok();
    writeln!(out).ok();
}

fn write_clause(out: &mut String, clause: &QedSpecClause, kani_valid: bool) {
    let commented = !kani_valid;
    let prefix = if commented { "  // [INVALID] " } else { "  " };
    let line = match clause.clause_type.as_ref() {
        "guard"       => format!("{}guard {}", prefix, clause.expression),
        "requires"    => format!("{}requires {}", prefix, clause.expression),
        "ensures"     => format!("{}ensures {}", prefix, clause.expression),
        "invariant"   => format!("{}invariant {}", prefix, clause.expression),
        "establishes" => format!("{}establishes {}", prefix, clause.expression),
        other         => format!("{}// unknown clause_type '{}': {}", prefix, other, clause.expression),
    };

    writeln!(out, "{}", line).ok();
}

fn to_pascal_case(s: &str) -> String {
    s.split(|c| c == '_' || c == '-')
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut chars = w.chars();
            match chars.next() {
                None    => String::new(),
                Some(c) => c.to_uppercase().to_string() + chars.as_str(),
            }
        })
        .collect()
}

pub fn write_to_file(
    path:    &std::path::Path,
    content: &str,
) -> anyhow::Result<()> {
    std::fs::write(path, content)
        .map_err(|e| anyhow::anyhow!("failed to write qedspec to {}: {}", path.display(), e))
}