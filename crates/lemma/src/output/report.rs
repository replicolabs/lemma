use std::fmt::Write;

use crate::types::{AnalysisResult, SecurityGap, Severity};

pub fn generate_markdown(result: &AnalysisResult) -> String {
    let mut out = String::with_capacity(4096);

    write_header(&mut out, result);
    write_executive_summary(&mut out, result);
    write_gap_details(&mut out, result);
    write_invariants_section(&mut out, result);
    write_footer(&mut out, result);

    out
}

fn write_header(out: &mut String, result: &AnalysisResult) {
    writeln!(out, "# Lemma Security Analysis Report").ok();
    writeln!(out).ok();
    writeln!(out, "| Field | Value |").ok();
    writeln!(out, "|---|---|").ok();
    writeln!(out, "| Program | `{}` |", result.program).ok();
    writeln!(out, "| Framework | {} |", result.framework).ok();
    writeln!(out, "| Program type | {} |", result.program_type).ok();
    writeln!(
        out,
        "| Security score | **{}/100** |",
        result.security_score
    )
    .ok();
    writeln!(out, "| Lemma version | {} |", result.lemma_version).ok();
    writeln!(out, "| Knowledge base | {} |", result.kb_version).ok();
    writeln!(
        out,
        "| Analysis date | {} |",
        &result.analysis_timestamp[..10]
    )
    .ok();
    if let Some(commit) = &result.git_commit {
        writeln!(out, "| Git commit | `{}` |", &commit[..7.min(commit.len())]).ok();
    }
    writeln!(out).ok();

    writeln!(out, "---").ok();
    writeln!(out).ok();
    writeln!(
        out,
        "> **Disclaimer:** This report was generated by an automated analysis tool. \
         It is not a substitute for a professional security audit. \
         All findings should be reviewed by a qualified security engineer \
         before deployment. This tool may produce false positives and may \
         miss vulnerabilities not covered by its knowledge base."
    )
    .ok();
    writeln!(out).ok();
}

fn write_executive_summary(out: &mut String, result: &AnalysisResult) {
    writeln!(out, "## Executive Summary").ok();
    writeln!(out).ok();

    let unacked: Vec<&SecurityGap> = result.gaps.iter().filter(|g| !g.acknowledged).collect();
    let acked: Vec<&SecurityGap> = result.gaps.iter().filter(|g| g.acknowledged).collect();

    let critical = unacked
        .iter()
        .filter(|g| g.severity == Severity::Critical)
        .count();
    let high = unacked
        .iter()
        .filter(|g| g.severity == Severity::High)
        .count();
    let medium = unacked
        .iter()
        .filter(|g| g.severity == Severity::Medium)
        .count();
    let low = unacked
        .iter()
        .filter(|g| g.severity == Severity::Low)
        .count();
    let info = unacked
        .iter()
        .filter(|g| g.severity == Severity::Informational)
        .count();

    writeln!(
        out,
        "The analysis identified **{}** security gap(s):\n",
        unacked.len()
    )
    .ok();
    writeln!(out, "| Severity | Count |").ok();
    writeln!(out, "|---|---|").ok();
    if critical > 0 {
        writeln!(out, "| 🔴 Critical | {} |", critical).ok();
    }
    if high > 0 {
        writeln!(out, "| 🟠 High | {} |", high).ok();
    }
    if medium > 0 {
        writeln!(out, "| 🟡 Medium | {} |", medium).ok();
    }
    if low > 0 {
        writeln!(out, "| 🔵 Low | {} |", low).ok();
    }
    if info > 0 {
        writeln!(out, "| ⚪ Informational | {} |", info).ok();
    }
    if !acked.is_empty() {
        writeln!(out, "| ✅ Acknowledged | {} |", acked.len()).ok();
    }
    writeln!(out).ok();
}

fn write_gap_details(out: &mut String, result: &AnalysisResult) {
    let unacked: Vec<&SecurityGap> = result.gaps.iter().filter(|g| !g.acknowledged).collect();

    if unacked.is_empty() {
        writeln!(out, "## Security Gaps").ok();
        writeln!(out).ok();
        writeln!(out, "No active security gaps found.").ok();
        writeln!(out).ok();
        return;
    }

    writeln!(out, "## Security Gaps").ok();
    writeln!(out).ok();

    for (i, gap) in unacked.iter().enumerate() {
        let severity_emoji = match gap.severity {
            Severity::Critical => "🔴",
            Severity::High => "🟠",
            Severity::Medium => "🟡",
            Severity::Low => "🔵",
            Severity::Informational => "⚪",
        };

        writeln!(
            out,
            "### {} {} — {} (`{}`)",
            severity_emoji, gap.id, gap.vuln_class, gap.handler_name,
        )
        .ok();
        writeln!(out).ok();
        writeln!(out, "**Severity:** {}  ", gap.severity).ok();
        writeln!(out, "**Handler:** `{}`  ", gap.handler_name).ok();
        writeln!(
            out,
            "**Source:** `{}` [{}]  ",
            gap.source_rule_id, gap.source
        )
        .ok();
        writeln!(out).ok();
        writeln!(out, "{}", gap.description).ok();
        writeln!(out).ok();

        if i < unacked.len() - 1 {
            writeln!(out, "---").ok();
            writeln!(out).ok();
        }
    }

    let acked: Vec<&SecurityGap> = result.gaps.iter().filter(|g| g.acknowledged).collect();
    if !acked.is_empty() {
        writeln!(out, "## Acknowledged Gaps").ok();
        writeln!(out).ok();
        writeln!(
            out,
            "The following gaps have been acknowledged by the development team:"
        )
        .ok();
        writeln!(out).ok();
        for gap in acked {
            let reason = gap.ack_reason.as_deref().unwrap_or("no reason given");
            writeln!(out, "- `{}` — {}: *{}*", gap.id, gap.vuln_class, reason).ok();
        }
        writeln!(out).ok();
    }
}

fn write_invariants_section(out: &mut String, result: &AnalysisResult) {
    if result.invariants.is_empty() {
        return;
    }

    writeln!(out, "## Generated Invariants").ok();
    writeln!(out).ok();
    writeln!(
        out,
        "The following formal invariants were generated for each analyzed handler. \
         These invariants are expressed in natural language, as Kani assertions, and \
         as QEDSpec clauses. A `.qedspec` file is generated alongside this report."
    )
    .ok();
    writeln!(out).ok();

    for inv in &result.invariants {
        writeln!(out, "### `{}`", inv.handler_name).ok();
        writeln!(out).ok();
        writeln!(out, "**Property:** {}", inv.natural_language).ok();
        writeln!(out, "**Confidence:** {:.0}%  ", inv.confidence * 100.0).ok();
        writeln!(out, "**Grounded in:** `{}`  ", inv.grounded_in).ok();
        writeln!(
            out,
            "**Kani valid:** {}  ",
            if inv.kani_valid {
                "✓"
            } else {
                "✗ — review required"
            }
        )
        .ok();
        writeln!(out).ok();

        if !inv.kani_assertion.is_empty() {
            writeln!(out, "```rust").ok();
            writeln!(out, "{}", inv.kani_assertion).ok();
            writeln!(out, "```").ok();
            writeln!(out).ok();
        }
    }
}

fn write_footer(out: &mut String, result: &AnalysisResult) {
    writeln!(out, "---").ok();
    writeln!(out).ok();
    writeln!(
        out,
        "*Generated by [Lemma](https://asklemma.xyz) {} | \
         Knowledge base {} | \
         Analysis: {}*",
        result.lemma_version,
        result.kb_version,
        &result.analysis_timestamp[..10],
    )
    .ok();
}

pub fn write_to_file(path: &std::path::Path, content: &str) -> anyhow::Result<()> {
    std::fs::write(path, content)
        .map_err(|e| anyhow::anyhow!("failed to write report to {}: {}", path.display(), e))
}
